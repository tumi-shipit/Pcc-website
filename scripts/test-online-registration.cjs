// Isolated PostgreSQL tests. Optional argument: installed @electric-sql/pglite path.
const { PGlite } = require(process.argv[2] || '../tmp/online-registration-tests/node_modules/@electric-sql/pglite');
const fs = require('node:fs');
const assert = require('node:assert/strict');
(async () => {
  const db = new PGlite();
  const event = '10000000-0000-4000-8000-000000000001';
  const other = '10000000-0000-4000-8000-000000000002';
  const section = '20000000-0000-4000-8000-000000000001';
  const otherSection = '20000000-0000-4000-8000-000000000002';
  const order = '30000000-0000-4000-8000-000000000001';
  try {
    await db.exec(`
      create role anon; create role authenticated; create role service_role;
      create schema auth;
      create function auth.uid() returns uuid language sql as $$ select nullif(current_setting('test.uid',true),'')::uuid $$;
      create function auth.jwt() returns jsonb language sql as $$ select jsonb_build_object('email',current_setting('test.email',true)) $$;
      create function public.current_admin_role() returns text language sql as $$ select nullif(current_setting('test.role',true),'') $$;
      create table tournaments(id uuid primary key, tournament_name text, entry_fee numeric default 50, registration_status text default 'Open', registration_schedule_enabled boolean default false, registration_open_date date, registration_close_date date);
      create table tournament_sections(id uuid primary key, tournament_id uuid references tournaments(id), entry_fee_override numeric, maximum_players integer);
      create table registrations(id uuid primary key default gen_random_uuid(), tournament_id uuid references tournaments(id), registration_status text default 'Pending',payment_status text default 'Pending',updated_at timestamptz);
      create table tournament_organiser_access(tournament_id uuid, organiser_email text, access_status text);
      create function effective_registration_status(text,boolean,date,date) returns text language sql as $$ select case when $2 then case when current_date between $3 and $4 then 'Open' else 'Closed' end else $1 end $$;
      grant usage on schema public to anon,authenticated,service_role;
    `);
    const workflow = fs.readFileSync('database/registration_admin_workflow.sql','utf8');
    await db.exec(workflow.slice(workflow.indexOf('create or replace function public.can_operate'), workflow.indexOf('create or replace function public.admin_batch')));
    await db.exec(fs.readFileSync('database/tournament_online_payments.sql','utf8'));
    await db.exec(fs.readFileSync('database/tournament_payment_required.sql','utf8'));
    await db.exec(fs.readFileSync('database/tournament_online_registration.sql','utf8'));
    await db.query('insert into tournaments(id) values($1),($2)',[event,other]);
    await db.query('insert into tournament_sections(id,tournament_id,maximum_players) values($1,$2,2),($3,$4,20)',[section,event,otherSection,other]);
    assert.equal((await db.query('select registration_mode from tournaments where id=$1',[event])).rows[0].registration_mode,'standard');
    await assert.rejects(db.query("select set_tournament_registration_mode($1,'lichess')",[event]), /Access denied/);
    await db.exec("set test.uid='90000000-0000-4000-8000-000000000001'; set test.email='organiser@example.com'");
    await db.query("insert into tournament_organiser_access values($1,'Organiser@Example.com','Active')",[event]);
    await db.query("select set_tournament_registration_mode($1,'lichess')",[event]);
    await assert.rejects(db.query("select set_tournament_registration_mode($1,'lichess')",[other]), /Access denied/);
    await db.exec("update tournament_organiser_access set access_status='Inactive'");
    await assert.rejects(db.query("select set_tournament_registration_mode($1,'chesscom')",[event]), /Access denied/);
    await db.exec("update tournament_organiser_access set access_status='Active'");
    await assert.rejects(db.query("select set_tournament_registration_mode($1,'invalid')",[event]), /Invalid registration mode/);
    await db.query('insert into registrations(tournament_id) values($1)',[other]);
    await db.exec("set test.role='admin'");
    await assert.rejects(db.query("select set_tournament_registration_mode($1,'chesscom')",[other]), /after entries exist/);
    await assert.rejects(db.query('insert into registrations(tournament_id) values($1)',[event]), /online tournament/);
    const submit = (username='OnlineUser', opts={}) => db.query('select submit_online_registration($1,$2,$3,$4,$5,$6,$7) as receipt',[
      opts.event || event, opts.section || section, opts.platform || 'lichess', opts.name ?? 'First', 'Surname', username, opts.email || 'contact@example.com'
    ]);
    await assert.rejects(submit('WrongPlatform',{platform:'chesscom'}), /Refresh/);
    await assert.rejects(submit('WrongSection',{section:otherSection}), /section/);
    await assert.rejects(submit('BadName',{name:' '}), /check constraint/);
    await assert.rejects(submit('BadEmail',{email:'not-an-email'}), /check constraint/);
    await assert.rejects(submit('@bad'), /check constraint/);
    const receipt=(await submit()).rows[0].receipt;
    assert.match(receipt.recoveryToken,/^[a-f0-9]{64}$/);
    assert.equal((await db.query('select count(*) from registrations')).rows[0].count,1);
    await assert.rejects(submit(' onlineuser '), /already registered/);
    await assert.rejects(db.query("update tournaments set registration_mode='standard' where id=$1",[event]), /after entries exist/);
    const settings=(await db.query('select get_tournament_registration_settings($1) as result',[event])).rows[0].result;
    assert.equal(settings.locked,true); assert.equal(settings.mode,'lichess');
    await db.exec("set test.role=''; set test.email='stranger@example.com'; set role authenticated");
    assert.equal((await db.query('select * from online_registrations')).rows.length,0);
    await assert.rejects(db.query('select * from online_registration_recovery'), /permission denied/);
    await assert.rejects(db.query("update online_registrations set payment_status='Paid'"), /permission denied/);
    await assert.rejects(db.query("select update_online_registration_status($1,'Approved')",[receipt.registrationId]), /Access denied/);
    await db.exec("reset role; set test.email='organiser@example.com'; set role authenticated");
    assert.equal((await db.query('select * from online_registrations')).rows.length,1);
    await db.exec('reset role');
    await db.query('select set_tournament_payment_required($1,true)',[event]);
    await assert.rejects(db.query("select update_online_registration_status($1,'Approved')",[receipt.registrationId]), /confirmed live/);
    await db.query("insert into registration_payment_orders(id,online_registration_id,tournament_id,amount) values($1,$2,$3,50)",[order,receipt.registrationId,event]);
    const pay=async (mode='live',amount=5000,currency='ZAR',id='payment-1')=>(await db.query('select complete_registration_payment_order($1,$2,$3,$4,$5) as ok',[order,id,mode,amount,currency])).rows[0].ok;
    assert.equal(await pay('test'),false); assert.equal(await pay('live',4999),false); assert.equal(await pay('live',5000,'USD'),false); assert.equal(await pay('live',5000,'ZAR',''),false);
    assert.equal((await db.query('select payment_status from online_registrations')).rows[0].payment_status,'Pending');
    assert.equal(await pay(),true); assert.equal(await pay(),true); assert.equal(await pay('live',5000,'ZAR','different-payment'),false);
    await db.query("select update_online_registration_status($1,'Approved')",[receipt.registrationId]);
    assert.equal((await db.query('select payment_status from online_registrations')).rows[0].payment_status,'Paid');
    const second=(await submit('Second')).rows[0].receipt;
    await assert.rejects(submit('Third'), /full/);
    await db.query('select set_tournament_payment_required($1,false)',[event]);
    await db.query("select update_online_registration_status($1,'Approved')",[second.registrationId]);
    await assert.rejects(db.query('select set_tournament_payment_required($1,true)',[event]), /Review approved online entries/);
    await db.query("update tournaments set registration_status='Closed' where id=$1",[event]);
    await assert.rejects(submit('Closed'), /closed/);
    await db.query("update tournaments set registration_status='Open',registration_schedule_enabled=true,registration_open_date=current_date-2,registration_close_date=current_date-1 where id=$1",[event]);
    await assert.rejects(submit('Expired'), /closed/);
    const third='10000000-0000-4000-8000-000000000003';
    const thirdSection='20000000-0000-4000-8000-000000000003';
    await db.exec("set test.role='admin'");
    await db.query('insert into tournaments(id) values($1)',[third]);
    await db.query('insert into tournament_sections(id,tournament_id) values($1,$2)',[thirdSection,third]);
    await db.query("select set_tournament_registration_mode($1,'chesscom')",[third]);
    await db.exec("set test.role=''; set test.uid=''; set role anon");
    await submit('OnlineUser',{event:third,section:thirdSection,platform:'chesscom'});
    await assert.rejects(db.query('select * from online_registrations'), /permission denied/);
    await assert.rejects(db.query("select complete_registration_payment_order($1,'fake','live',5000,'ZAR')",[order]), /permission denied/);
    await db.exec('reset role');
    assert.equal((await db.query('select count(*) from online_registrations')).rows[0].count,3);
    console.log('PASS: defaults, admin/assigned-organiser permissions, inactive/unassigned denial, mode locks for both entry types, legacy submission guard, input/section validation, duplicate normalization, RLS/privacy, capacity, payment validation/idempotency, approval gates, closed/scheduled events.');
  } finally { await db.close(); }
})().catch(error=>{console.error(error);process.exitCode=1;});
